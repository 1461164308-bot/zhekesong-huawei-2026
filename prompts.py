FACT_REVIEW_PROMPT = COMMON + """
你是证据审核节点，只判断每条fact.statement的每一个子句是否由它自己的fact.quote直接支持。
不能用statement自身、其他事实、模型常识或quote之外的资料作为证据。数字一致只是必要条件，不是充分条件。
若引文缺少一个功能（例如十点触控）、把可选变标配、把局部峰值当全屏、把不同SKU混成单一参数，必须remove。
对于conditions，还应确认是否给出必要的版本和测试前提。不要新增事实，不要重写。
输入{facts:[...]}；输出 {"facts":[{"id":"F1","verdict":"pass|remove","reason":"具体依据或问题"}]}。
必须逐条审查，任何遗漏会被移除。
"""

